//! Lock-recovery chokepoint gate: outside `src/sync_util.rs`, in a **non-test**
//! region, no file may privately re-define a lock-recovery helper, nor hand-inline
//! its body, without being named in a register.
//!
//! # Why this gate exists (measured, not supposed)
//!
//! This is repair **#3** of one named class with **no grader between any of them**:
//!
//! * Day 58 — `lock_or_recover` extracted (Mutex).
//! * Day 109 — `rw_read_or_recover` / `rw_write_or_recover` extracted (RwLock), with
//!   a module doc claiming it deduplicated copies in `watch`, `commands_fork`,
//!   `commands_stash` and `commands_todo`. It converted **1 of the 4 files it named**.
//! * Day 193 (#900) — the remaining **6** byte-identical private copies deleted from
//!   `commands_fork.rs`, `commands_stash.rs` and `commands_todo.rs`.
//!
//! So a false authoritative claim sat in the shared module's own doc comment for
//! **84 days**, and blind round 94 found it only by reading the files. My stopping
//! rule fires at N>=3 repairs with no grader between them: the diff must become an
//! **instrument**, not a fourth fix.
//!
//! # The self-concealing property, which is the whole argument for a gate
//!
//! A private copy shares the shared module's **exact** names, so `grep lock_or_recover`
//! counts a *definition* as a *use* of the shared helper. That is precisely how Day
//! 109's claim survived 84 days while being false, and why round 94's own first-pass
//! census reported 69 helper call sites before resolving imports. **No name-based
//! search can catch this.** Only a scan that asks *"is this a definition or a call?"*
//! can — which is what this gate does.
//!
//! # The rule
//!
//! Outside [`CHOKEPOINT_FILE`], in a non-test region, neither of these may appear
//! unregistered:
//!
//! * **A definition** — `fn lock_or_recover`, `fn rw_read_or_recover`,
//!   `fn rw_write_or_recover`. The class that actually bit.
//! * **A hand-inlined body** — `unwrap_or_else(` and `into_inner()` on one line.
//!   Round 94 counted 5 of these; #900 named them as out of scope, so they ship as
//!   registered debt.
//!
//! Two branches, running in **opposite directions**: an unregistered occurrence is
//! fatal (with both remedies printed verbatim), and a registered entry that no longer
//! occurs is *also* fatal — the ratchet, since an exception list only pays itself down
//! if improving is a failure too.
//!
//! # Deliberately NOT using the shared brace scanner
//!
//! `tests/common/mod.rs` holds a brace scanner (#835). This gate deliberately does
//! **not** consume it: a line scan plus test-region truncation is sufficient here and
//! much smaller, which is the same decision `tests/git_chokepoint.rs` records. Do not
//! "fix" this by wiring in the scanner.

use std::io::Write;
use std::path::Path;

/// The one file that *is* the chokepoint, and is exempt by definition.
const CHOKEPOINT_FILE: &str = "src/sync_util.rs";

/// Hand-inlined lock-recovery bodies outside the chokepoint that are deliberately
